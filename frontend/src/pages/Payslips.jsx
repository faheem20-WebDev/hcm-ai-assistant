import React, { useState, useEffect } from 'react';
import api from '../api';
import Loading from '../components/Loading';
import Empty from '../components/Empty';
import ErrorBox from '../components/ErrorBox';

const Payslips = () => {
  const [payslips, setPayslips] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [downloadingId, setDownloadingId] = useState(null);

  const fetchPayslips = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await api.get('/payslips/me');
      const list = res.data?.items || (Array.isArray(res.data) ? res.data : []);
      setPayslips(list);
    } catch (err) {
      setError(err?.response?.data?.error || 'Failed to retrieve payslips.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchPayslips();
  }, []);

  const handleDownloadPdf = async (id, month) => {
    setDownloadingId(id);
    try {
      const res = await api.get(`/payslips/${id}/pdf`, { responseType: 'blob' });
      const blob = new Blob([res.data], { type: 'application/pdf' });
      const url = window.URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `Payslip-${month || id}.pdf`);
      document.body.appendChild(link);
      link.click();
      link.remove();
      window.URL.revokeObjectURL(url);
    } catch (err) {
      alert('Failed to download PDF payslip: ' + (err?.response?.data?.error || err.message));
    } finally {
      setDownloadingId(null);
    }
  };

  return (
    <div style={{ display: 'flex', flexDirection: 'column', gap: '1.5rem', animation: 'fadeIn 0.25s ease' }}>
      <div className="page-header" style={{ marginBottom: 0 }}>
        <div className="page-header-info">
          <h1>My Payslips</h1>
          <p>Access and download your finalized monthly salary statements and statutory tax breakdowns.</p>
        </div>
      </div>

      <ErrorBox error={error} onRetry={fetchPayslips} />

      {loading && <Loading message="Loading your payslips..." />}

      {!loading && (
        payslips.length === 0 ? (
          <Empty
            title="No payslips issued"
            description="Finalized monthly payslips generated by HR will appear here."
          />
        ) : (
          <div className="table-container">
            <table className="table">
              <thead>
                <tr>
                  <th>Month</th>
                  <th style={{ textAlign: 'right' }}>Basic Salary</th>
                  <th style={{ textAlign: 'right' }}>Gross (1.5x)</th>
                  <th style={{ textAlign: 'right' }}>Tax Withholding</th>
                  <th style={{ textAlign: 'right' }}>Net Disbursed</th>
                  <th style={{ textAlign: 'right' }}>Action</th>
                </tr>
              </thead>
              <tbody>
                {payslips.map((p) => {
                  const id = p.id || p._id || p.month;
                  return (
                    <tr key={id}>
                      <td style={{ fontWeight: 600, color: 'var(--text)' }}>
                        {p.month}
                      </td>
                      <td style={{ textAlign: 'right', color: 'var(--text-muted)' }}>
                        PKR {(p.basic || 0).toLocaleString()}
                      </td>
                      <td style={{ textAlign: 'right', fontWeight: 600, color: 'var(--text)' }}>
                        PKR {(p.gross || 0).toLocaleString()}
                      </td>
                      <td style={{ textAlign: 'right', color: 'var(--danger)' }}>
                        PKR {(p.tax || 0).toLocaleString()}
                      </td>
                      <td style={{ textAlign: 'right', fontWeight: 700, color: 'var(--success)' }}>
                        PKR {(p.net || 0).toLocaleString()}
                      </td>
                      <td style={{ textAlign: 'right' }}>
                        <button
                          type="button"
                          onClick={() => handleDownloadPdf(id, p.month)}
                          disabled={downloadingId === id}
                          className="btn btn-primary btn-sm"
                          style={{ gap: '0.4rem' }}
                        >
                          <svg width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round">
                            <path d="M21 15v4a2 2 0 0 1-2 2H5a2 2 0 0 1-2-2v-4M7 10l5 5 5-5M12 15V3" />
                          </svg>
                          {downloadingId === id ? 'Downloading...' : 'Download PDF'}
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )
      )}
    </div>
  );
};

export default Payslips;
