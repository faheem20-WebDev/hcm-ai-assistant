import React, { useState, useEffect } from 'react';
import api from '../api';
import Loading from '../components/Loading';
import Empty from '../components/Empty';
import ErrorBox from '../components/ErrorBox';

const Payslips = () => {
  const [payslips, setPayslips] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  const [downloadingId, setDownloadingId] = useState(null);

  const fetchPayslips = async () => {
    setLoading(true);
    setError(null);
    try {
      const res = await api.get('/payslips/me');
      const list = res.data?.items || (Array.isArray(res.data) ? res.data : []);
      setPayslips(list);
    } catch (err) {
      setError(err?.response?.data?.error || 'Failed to retrieve payslips.');
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchPayslips();
  }, []);

  const handleDownloadPdf = async (id, month) => {
    setDownloadingId(id);
    try {
      const res = await api.get(`/payslips/${id}/pdf`, { responseType: 'blob' });
      const blob = new Blob([res.data], { type: 'application/pdf' });
      const url = window.URL.createObjectURL(blob);
      const link = document.createElement('a');
      link.href = url;
      link.setAttribute('download', `Payslip-${month || id}.pdf`);
      document.body.appendChild(link);
      link.click();
      link.remove();
      window.URL.revokeObjectURL(url);
    } catch (err) {
      alert('Failed to download PDF payslip: ' + (err?.response?.data?.error || err.message));
    } finally {
      setDownloadingId(null);
    }
  };

  return (
    <div>
      <div style={{ marginBottom: '1.5rem' }}>
        <h1 style={{ fontSize: '1.5rem', fontWeight: '700', color: '#0f172a', margin: '0 0 0.25rem 0' }}>
          My Payslips
        </h1>
        <p style={{ margin: 0, color: '#64748b', fontSize: '0.875rem' }}>
          Access and download your finalized monthly salary statements and statutory tax breakdowns.
        </p>
      </div>

      <ErrorBox error={error} onRetry={fetchPayslips} />

      {loading && <Loading message="Loading your payslips..." />}

      {!loading && (
        payslips.length === 0 ? (
          <Empty
            title="No payslips issued"
            description="Finalized monthly payslips generated by HR will appear here."
          />
        ) : (
          <div style={{ backgroundColor: '#ffffff', border: '1px solid #e2e8f0', borderRadius: '8px', overflow: 'hidden' }}>
            <table style={{ width: '100%', borderCollapse: 'collapse', textAlign: 'left', fontSize: '0.875rem' }}>
              <thead style={{ backgroundColor: '#f8fafc', borderBottom: '1px solid #e2e8f0' }}>
                <tr>
                  <th style={{ padding: '0.85rem 1rem', color: '#475569', fontWeight: '600' }}>Month</th>
                  <th style={{ padding: '0.85rem 1rem', color: '#475569', fontWeight: '600', textAlign: 'right' }}>Basic Salary</th>
                  <th style={{ padding: '0.85rem 1rem', color: '#475569', fontWeight: '600', textAlign: 'right' }}>Gross (1.5x)</th>
                  <th style={{ padding: '0.85rem 1rem', color: '#475569', fontWeight: '600', textAlign: 'right' }}>Tax Withholding</th>
                  <th style={{ padding: '0.85rem 1rem', color: '#475569', fontWeight: '600', textAlign: 'right' }}>Net Disbursed</th>
                  <th style={{ padding: '0.85rem 1rem', textAlign: 'right', color: '#475569', fontWeight: '600' }}>Action</th>
                </tr>
              </thead>
              <tbody>
                {payslips.map((p) => {
                  const id = p.id || p._id || p.month;
                  return (
                    <tr key={id} style={{ borderBottom: '1px solid #f1f5f9' }}>
                      <td style={{ padding: '0.85rem 1rem', fontWeight: '600', color: '#1e293b' }}>
                        {p.month}
                      </td>
                      <td style={{ padding: '0.85rem 1rem', textAlign: 'right', color: '#475569' }}>
                        PKR {(p.basic || 0).toLocaleString()}
                      </td>
                      <td style={{ padding: '0.85rem 1rem', textAlign: 'right', fontWeight: '600', color: '#1e293b' }}>
                        PKR {(p.gross || 0).toLocaleString()}
                      </td>
                      <td style={{ padding: '0.85rem 1rem', textAlign: 'right', color: '#dc2626' }}>
                        PKR {(p.tax || 0).toLocaleString()}
                      </td>
                      <td style={{ padding: '0.85rem 1rem', textAlign: 'right', fontWeight: '700', color: '#16a34a' }}>
                        PKR {(p.net || 0).toLocaleString()}
                      </td>
                      <td style={{ padding: '0.85rem 1rem', textAlign: 'right' }}>
                        <button
                          onClick={() => handleDownloadPdf(id, p.month)}
                          disabled={downloadingId === id}
                          style={{
                            backgroundColor: '#2563eb',
                            color: '#ffffff',
                            border: 'none',
                            borderRadius: '4px',
                            padding: '0.35rem 0.75rem',
                            fontSize: '0.8rem',
                            fontWeight: '600',
                            cursor: downloadingId === id ? 'not-allowed' : 'pointer',
                            opacity: downloadingId === id ? 0.6 : 1
                          }}
                        >
                          {downloadingId === id ? 'Downloading...' : '📥 Download PDF'}
                        </button>
                      </td>
                    </tr>
                  );
                })}
              </tbody>
            </table>
          </div>
        )
      )}
    </div>
  );
};

export default Payslips;
